"""Classical solvers for the Duffing-type BVP: collocation, shooting, finite differences.

    y'' + y + eps y^3 = 0  on [0, pi],   y(0) = 1,   y'(pi) = 0,   eps = 0.1.

Book: Chapter 5, Section "Comparison with classical methods" (table generated by
make_tables.py from this script's results.json and from duffing_pinn.py's results.json).

Methods (all converge to the smallest-amplitude solution A_1 = y(pi) = -1.00704...):

* collocation: scipy.integrate.solve_bvp (fourth-order collocation with residual control,
  Kierzenka and Shampine 2001), 11 initial nodes, zero initial guess, tol in {1e-3, 1e-6, 1e-9};
* shooting: unknown slope s = y'(0); the IVP is integrated with DOP853 (rtol = atol = tol) and
  y'(pi; s) = 0 is solved with Brent's method on the bracket [-1, 1], tol in {1e-4, 1e-7, 1e-10};
* finite differences: second-order central differences on N uniform intervals (ghost point
  for the Neumann condition at pi), Newton's method with a tridiagonal Jacobian,
  N in {100, 1000, 10000}.

Errors are measured against the closed-form solution on 1001 uniform points of [0, pi]
(collocation: its C^1 cubic interpolant; shooting: DOP853 dense output; finite
differences: cubic-spline interpolation of the nodal values). Times are medians over
repeated solves (wall-clock and CPU time of one thread are both recorded).

Run:  PYTHONPATH=. python chapters/ch05_bvp/duffing_classical.py          (well under a minute)
      PYTHONPATH=. python chapters/ch05_bvp/duffing_classical.py --quick
"""
from __future__ import annotations

import numpy as np
from scipy.integrate import solve_bvp, solve_ivp
from scipy.interpolate import CubicSpline
from scipy.linalg import solve_banded
from scipy.optimize import brentq

from pinnode import Example, linf, rel_l2

from _bvp_common import (DY_END, EPS_DUFFING, T_END, Y0, duffing_A1, duffing_bc_residual,
                         duffing_exact, duffing_rhs_system, time_call)


def collocation(tol: float):
    x0 = np.linspace(0.0, T_END, 11)
    sol = solve_bvp(duffing_rhs_system, duffing_bc_residual, x0, np.zeros((2, x0.size)),
                    tol=tol, max_nodes=100000)
    if not sol.success:
        raise RuntimeError(sol.message)
    return sol


def _rhs(t, z):
    return [z[1], -z[0] - EPS_DUFFING * z[0] ** 3]


def shooting(tol: float):
    def G(s):
        return solve_ivp(_rhs, (0.0, T_END), [Y0, s], method="DOP853", rtol=tol, atol=tol).y[1, -1] - DY_END

    s, info = brentq(G, -1.0, 1.0, xtol=max(1e-2 * tol, 1e-15), full_output=True)
    sol = solve_ivp(_rhs, (0.0, T_END), [Y0, s], method="DOP853", rtol=tol, atol=tol, dense_output=True)
    return s, sol, info.iterations


def finite_differences(N: int, newton_tol: float = 1e-13, maxit: int = 50):
    h = T_END / N
    u = np.zeros(N)                       # unknowns y_1, ..., y_N (y_0 = Y0 is known)
    it = 0
    for it in range(1, maxit + 1):
        y = np.concatenate([[Y0], u])
        F = np.empty(N)
        F[:-1] = (y[:-2] - 2.0 * y[1:-1] + y[2:]) / h ** 2 + y[1:-1] + EPS_DUFFING * y[1:-1] ** 3
        # Neumann condition at t_N = pi through the ghost value y_{N+1} = y_{N-1} + 2 h DY_END
        F[-1] = (2.0 * y[-2] - 2.0 * y[-1] + 2.0 * h * DY_END) / h ** 2 + y[-1] + EPS_DUFFING * y[-1] ** 3
        ab = np.zeros((3, N))
        ab[0, 1:] = 1.0 / h ** 2
        ab[1, :] = -2.0 / h ** 2 + 1.0 + 3.0 * EPS_DUFFING * u ** 2
        ab[2, :-1] = 1.0 / h ** 2
        ab[2, N - 2] = 2.0 / h ** 2
        du = solve_banded((1, 1), ab, -F)
        u += du
        if np.max(np.abs(du)) < newton_tol:
            break
    return np.linspace(0.0, T_END, N + 1), np.concatenate([[Y0], u]), it


def main():
    ex = Example("ch05_bvp", "duffing_classical",
                 description="Duffing-type BVP: collocation, shooting and finite differences (accuracy, time)",
                 default_seed=1234)
    t = np.linspace(0.0, T_END, 1001)
    y_ref = duffing_exact(t, duffing_A1())
    reps = dict(min_repeats=ex.pick(7, 1), min_total=ex.pick(0.5, 0.0))
    rows = []

    for tol in ex.pick([1e-3, 1e-6, 1e-9], [1e-3]):
        sol, wall, cpu, n = time_call(lambda: collocation(tol), **reps)
        y = sol.sol(t)[0]
        rows.append({"method": "collocation (solve_bvp)", "setting": f"tol = {tol:.0e}", "param": tol,
                     "size": int(sol.x.size), "size_name": "mesh nodes",
                     "rel_l2": rel_l2(y, y_ref), "linf": linf(y, y_ref),
                     "wall_time_s": wall, "cpu_time_s": cpu, "repeats": n})

    for tol in ex.pick([1e-4, 1e-7, 1e-10], [1e-4]):
        (s, sol, iters), wall, cpu, n = time_call(lambda: shooting(tol), **reps)
        y = sol.sol(t)[0]
        rows.append({"method": "shooting (DOP853 + Brent)", "setting": f"rtol = {tol:.0e}", "param": tol,
                     "size": int(iters), "size_name": "root-finder iterations", "slope_y'(0)": s,
                     "rel_l2": rel_l2(y, y_ref), "linf": linf(y, y_ref),
                     "wall_time_s": wall, "cpu_time_s": cpu, "repeats": n})

    for N in ex.pick([100, 1000, 10000], [100]):
        (tn, yn, its), wall, cpu, n = time_call(lambda: finite_differences(N), **reps)
        y = CubicSpline(tn, yn)(t)
        rows.append({"method": "finite differences + Newton", "setting": f"N = {N}", "param": N,
                     "size": int(its), "size_name": "Newton iterations",
                     "rel_l2": rel_l2(y, y_ref), "linf": linf(y, y_ref),
                     "wall_time_s": wall, "cpu_time_s": cpu, "repeats": n})

    for r in rows:
        ex.log(f"{r['method']:28s} {r['setting']:12s} relL2={r['rel_l2']:.2e} linf={r['linf']:.2e} "
               f"{r['size_name']}={r['size']}  wall={r['wall_time_s']*1e3:.2f} ms  cpu={r['cpu_time_s']*1e3:.2f} ms")
    ex.save_table(rows, "classical")
    ex.save_results({"problem": {"eps": EPS_DUFFING, "interval": [0.0, T_END], "bc": "y(0)=1, y'(pi)=0",
                                 "reference": "closed form (Jacobi cn), smallest-amplitude solution"},
                     "test_grid": "1001 uniform points on [0, pi]",
                     "timing": "median over repeated solves; wall-clock and CPU time of one thread",
                     "rows": rows})


if __name__ == "__main__":
    main()
