"""Write the LaTeX tables of Chapter 4 from the results files; time the classical solvers.

Book: Chapter 4 (Initial value problems), tables ivp:tab:manual, ivp:tab:logistic, ivp:tab:vdp,
ivp:tab:lv and ivp:tab:cost (Section "How accurate and how fast?").

Run this script AFTER manual_single_point.py, logistic_activation_study.py, vanderpol.py and
lotka_volterra.py (scripts/run_all.py runs the folder in alphabetical order, so this file is
named to come last). It

1. reads outputs/ch04_ivp/<example>/{results.json, summary.csv, gradient_table.csv};
2. for each worked example solves the IVP with SciPy's RK45 (Dormand-Prince 5(4)) for
   rtol = atol = 10^-2, 10^-2.5, ..., 10^-12 and keeps the loosest tolerance whose relative L2
   error on the 1001-point test grid does not exceed the PINN's error; it also runs DOP853 at
   rtol = atol = 1e-12. Errors are measured against the exact solution (logistic) or against
   DOP853 at rtol = atol = 2.5e-14. Times are the best of several repetitions;
3. writes tab_manual.tex, tab_logistic.tex, tab_vdp.tex, tab_lv.tex and tab_cost.tex
   (booktabs/siunitx tabular environments, \\input by the chapter) to the output folder and,
   with --table-dir, also to the book: --table-dir ../book/figures/ch04

Training and run times depend on the machine and its load; regenerate the cost table on an
idle machine after re-running the PINN scripts.

Run:  python chapters/ch04_ivp/write_tables.py --table-dir ../book/figures/ch04   (about 10 s)
      python chapters/ch04_ivp/write_tables.py --quick                           (smoke test)
"""
from __future__ import annotations

import json
import math
import time
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.integrate import solve_ivp

from pinnode import Example, rel_l2
from pinnode.utils import OUTPUT_ROOT

CHAPTER = "ch04_ivp"


# ----------------------------------------------------------------------------- formatting
def num(x, digits: int = 2) -> str:
    """\\num{...} with `digits` significant digits (scientific notation below 1e-2)."""
    if x is None or (isinstance(x, float) and not math.isfinite(x)):
        return "--"
    x = float(x)
    if x == 0.0:
        return "\\num{0}"
    if abs(x) < 1e-2 or abs(x) >= 1e5:
        m, e = f"{x:.{digits - 1}e}".split("e")
        return f"\\num{{{m}e{int(e)}}}"
    return f"\\num{{{x:.{max(digits - 1 - int(math.floor(math.log10(abs(x)))), 0)}f}}}"


def integer(x) -> str:
    return "--" if x is None or (isinstance(x, float) and not math.isfinite(x)) else f"\\num{{{int(x)}}}"


def load_json(path: Path):
    return json.loads(path.read_text()) if path.exists() else None


def load_csv(path: Path):
    return pd.read_csv(path) if path.exists() else None


HEADER = "% Generated by repo/chapters/ch04_ivp/write_tables.py -- do not edit by hand.\n"


# ----------------------------------------------------------------------------- tables
def table_manual(df) -> str:
    names = {"w1": "$w_1$", "w2": "$w_2$", "b1": "$b_1$", "b2": "$b_2$", "v1": "$v_1$", "v2": "$v_2$",
             "c": "$c$"}
    lines = [HEADER, "\\begin{tabular}{lrrrrr}", "\\toprule",
             "$\\theta$ & value & $\\partial\\Loss_r/\\partial\\theta$ & $\\partial\\Loss_{ic}/\\partial\\theta$ "
             "& $\\partial\\Loss/\\partial\\theta$ & after one Adam step \\\\", "\\midrule"]
    if df is None:
        lines.append("\\multicolumn{6}{c}{(run manual\\_single\\_point.py)} \\\\")
    else:
        for _, r in df.iterrows():
            lines.append(f"{names[r['parameter']]} & \\num{{{r['theta']:.1f}}} & \\num{{{r['dLr_dtheta']:.6f}}} & "
                         f"\\num{{{r['dLic_dtheta']:.6f}}} & \\num{{{r['dL_dtheta']:.6f}}} & "
                         f"\\num{{{r['theta_after_adam']:.6f}}} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def table_logistic(df) -> str:
    labels = {"tanh": "tanh", "sigmoid": "sigmoid", "relu": "ReLU", "swish": "swish"}
    lines = [HEADER, "\\begin{tabular}{llccccc}", "\\toprule",
             "initial & activation & \\multicolumn{2}{c}{relative $L^2$ error} & maximum & "
             "$|y_\\theta(0)-y_0|$ & final \\\\",
             "\\cmidrule(lr){3-4}",
             "condition & & after Adam & final & error & & loss \\\\", "\\midrule"]
    if df is None:
        lines.append("\\multicolumn{7}{c}{(run logistic\\_activation\\_study.py)} \\\\")
    else:
        for i, (_, r) in enumerate(df.iterrows()):
            if i == 4:
                lines.append("\\midrule")
            ic = "exact" if r["formulation"] == "hard" else num(r["abs_ic_error"])
            lines.append(f"{r['formulation']} & {labels[r['activation']]} & {num(r['rel_l2_after_adam'])} & "
                         f"{num(r['rel_l2'])} & {num(r['linf'])} & {ic} & {num(r['final_loss'])} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def table_vdp(res) -> str:
    lines = [HEADER, "\\begin{tabular}{lcccccc}", "\\toprule",
             "initial conditions & \\multicolumn{2}{c}{error of $y_\\theta$} & \\multicolumn{2}{c}{error of $y_\\theta'$} & "
             "max.\\ residual & final loss \\\\",
             "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}",
             " & rel.\\ $L^2$ & max. & rel.\\ $L^2$ & max. & on test grid & \\\\", "\\midrule"]
    labels = {"hard_bounded": "hard, $\\varphi=t^2/(1+t^2)$", "hard_power": "hard, $\\varphi=t^2$",
              "soft": "soft, $\\lambda_{ic}=1$", "hard": "hard", }
    if res is None:
        lines.append("\\multicolumn{7}{c}{(run vanderpol.py)} \\\\")
    else:
        for r in res["summary"]:
            lines.append(f"{labels.get(r['formulation'], r['formulation'])} & {num(r['rel_l2'])} & "
                         f"{num(r['linf'])} & {num(r['rel_l2_dy'])} & "
                         f"{num(r['linf_dy'])} & {num(r['max_abs_residual'])} & {num(r['final_loss'])} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def table_lv(res) -> str:
    lines = [HEADER, "\\begin{tabular}{lcc}", "\\toprule", " & prey $y_1$ & predator $y_2$ \\\\", "\\midrule"]
    if res is None:
        lines.append("\\multicolumn{3}{c}{(run lotka\\_volterra.py)} \\\\")
    else:
        lines += [f"relative $L^2$ error & {num(res['rel_l2_prey'])} & {num(res['rel_l2_predator'])} \\\\",
                  f"maximum error & {num(res['linf_prey'])} & {num(res['linf_predator'])} \\\\",
                  f"maximum residual (log variables) & \\multicolumn{{2}}{{c}}{{{num(res['max_abs_residual_log'])}}} \\\\",
                  f"drift $\\max_t|H(y_\\theta(t))-H(y(0))|$ & \\multicolumn{{2}}{{c}}{{{num(res['H_drift_pinn'])}}} \\\\",
                  f"final loss & \\multicolumn{{2}}{{c}}{{{num(res['final_loss'])}}} \\\\"]
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def table_third_order(res) -> str:
    lines = [HEADER, "\\begin{tabular}{lcc}", "\\toprule", " & $y_1$ & $y_2$ \\\\", "\\midrule"]
    if res is None:
        lines.append("\\multicolumn{3}{c}{(run third\\_order\\_system.py)} \\\\")
    else:
        lines += [f"relative $L^2$ error & {num(res['rel_l2_y1'])} & {num(res['rel_l2_y2'])} \\\\",
                  f"maximum error & {num(res['linf_y1'])} & {num(res['linf_y2'])} \\\\",
                  f"maximum residual & \\multicolumn{{2}}{{c}}{{{num(res['max_abs_residual'])}}} \\\\",
                  f"final loss & \\multicolumn{{2}}{{c}}{{{num(res['final_loss'])}}} \\\\"]
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


# ----------------------------------------------------------------------------- classical solvers
def logistic_problem():
    r, y0, T = 2.0, 0.1, 2.0
    t = np.linspace(0.0, T, 1001)
    exact = (y0 * np.exp(r * t) / (1.0 + y0 * (np.exp(r * t) - 1.0))).reshape(-1, 1)
    return {"f": lambda s, y: r * y * (1.0 - y), "span": (0.0, T), "y0": [y0], "t": t, "truth": exact}


def vdp_problem():
    mu = 0.5
    f = lambda s, z: [z[1], mu * (1.0 - z[0] ** 2) * z[1] - z[0]]
    t = np.linspace(0.0, 10.0, 1001)
    return {"f": f, "span": (0.0, 10.0), "y0": [1.0, 0.0], "t": t, "component": [0]}


def lv_problem(T=15.0):
    a, b, c, d = 1.0, 0.1, 1.5, 0.075
    f = lambda s, y: [a * y[0] - b * y[0] * y[1], -c * y[1] + d * y[0] * y[1]]
    t = np.linspace(0.0, T, 1001)
    return {"f": f, "span": (0.0, T), "y0": [10.0, 5.0], "t": t}


def solve(prob, method, tol, repeats):
    best, sol = math.inf, None
    for _ in range(repeats):
        t0 = time.perf_counter()
        sol = solve_ivp(prob["f"], prob["span"], prob["y0"], method=method, t_eval=prob["t"],
                        rtol=tol, atol=tol)
        best = min(best, time.perf_counter() - t0)
    y = sol.y.T
    if "component" in prob:
        y = y[:, prob["component"]]
    return y, sol.nfev, best


def classical_costs(prob, pinn_err, repeats):
    if "truth" not in prob:
        truth = solve_ivp(prob["f"], prob["span"], prob["y0"], method="DOP853", t_eval=prob["t"],
                          rtol=2.5e-14, atol=2.5e-14).y.T
        prob["truth"] = truth[:, prob["component"]] if "component" in prob else truth
    out = {}
    y, nfev, tm = solve(prob, "DOP853", 1e-12, repeats)
    out["dop853"] = {"tol": 1e-12, "nfev": nfev, "time_s": tm, "rel_l2": rel_l2(y, prob["truth"])}
    sweep = []
    for k in np.arange(2.0, 12.01, 0.5):
        tol = 10.0 ** (-k)
        y, nfev, tm = solve(prob, "RK45", tol, repeats)
        sweep.append({"tol": tol, "nfev": nfev, "time_s": tm, "rel_l2": rel_l2(y, prob["truth"])})
    out["rk45_sweep"] = sweep
    match = None
    if pinn_err is not None and math.isfinite(pinn_err):
        match = next((s for s in sweep if s["rel_l2"] <= pinn_err), None)
    out["rk45_matched"] = match
    return out


def table_cost(entries) -> str:
    cols = [e["label"] for e in entries]
    def row(label, vals):
        return f"{label} & " + " & ".join(vals) + " \\\\"
    lines = [HEADER, "\\begin{tabular}{l" + "c" * len(cols) + "}", "\\toprule",
             " & " + " & ".join(cols) + " \\\\", "\\midrule",
             f"\\multicolumn{{{len(cols) + 1}}}{{l}}{{\\emph{{PINN (Adam, then L-BFGS)}}}} \\\\"]
    lines.append(row("\\quad relative $L^2$ error", [num(e["pinn"].get("rel_l2")) for e in entries]))
    lines.append(row("\\quad optimizer iterations", [integer(e["pinn"].get("iterations")) for e in entries]))
    lines.append(row("\\quad collocation points $M$", [integer(e["pinn"].get("collocation")) for e in entries]))
    lines.append(row("\\quad training time [s]", [num(e["pinn"].get("train_time_s")) for e in entries]))
    lines.append("\\midrule")
    lines.append(f"\\multicolumn{{{len(cols) + 1}}}{{l}}{{\\emph{{RK45 at the accuracy of the PINN}}}} \\\\")
    m = [e["classical"]["rk45_matched"] or {} for e in entries]
    lines.append(row("\\quad tolerance (rtol $=$ atol)", [num(x.get("tol"), 2) for x in m]))
    lines.append(row("\\quad evaluations of $f$", [integer(x.get("nfev")) for x in m]))
    lines.append(row("\\quad relative $L^2$ error", [num(x.get("rel_l2")) for x in m]))
    lines.append(row("\\quad time [ms]", [num(1e3 * x["time_s"]) if x else "--" for x in m]))
    lines.append("\\midrule")
    lines.append(f"\\multicolumn{{{len(cols) + 1}}}{{l}}{{\\emph{{DOP853, rtol $=$ atol $=10^{{-12}}$}}}} \\\\")
    dp = [e["classical"]["dop853"] for e in entries]
    lines.append(row("\\quad evaluations of $f$", [integer(x["nfev"]) for x in dp]))
    lines.append(row("\\quad relative $L^2$ error", [num(x["rel_l2"]) for x in dp]))
    lines.append(row("\\quad time [ms]", [num(1e3 * x["time_s"]) for x in dp]))
    lines.append("\\midrule")
    ratios = []
    for e, x in zip(entries, m):
        tp = e["pinn"].get("train_time_s")
        if x and tp:
            m, e = f"{tp / x['time_s']:.0e}".split("e")       # order of magnitude, e.g. 9e4
            ratios.append(f"\\num{{{m}e{int(e)}}}")
        else:
            ratios.append("--")
    lines.append(row("time ratio PINN\\,/\\,RK45", ratios))
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def main():
    ex = Example(CHAPTER, "write_tables", description="LaTeX tables of Chapter 4 and classical solver costs",
                 default_seed=0,
                 extra_args=[(("--table-dir",), {"default": None, "help": "also write the .tex tables here"}),
                             (("--results-root",), {"default": str(OUTPUT_ROOT / CHAPTER),
                                                    "help": "folder with the example outputs"})])
    root = Path(ex.args.results_root)
    repeats = ex.pick(20, 2)

    manual = load_csv(root / "manual_single_point" / "gradient_table.csv")
    logistic = load_csv(root / "logistic_activation_study" / "summary.csv")
    logistic_res = load_json(root / "logistic_activation_study" / "results.json")
    vdp = load_json(root / "vanderpol" / "results.json")
    lv = load_json(root / "lotka_volterra" / "results.json")
    third = load_json(root / "third_order_system" / "results.json")

    # PINN results entering the cost table
    pinn = {}
    if logistic is not None:
        r = logistic[(logistic.formulation == "hard") & (logistic.activation == "tanh")].iloc[0]
        pinn["logistic"] = {"rel_l2": float(r["rel_l2"]), "iterations": int(r["iterations"]),
                            "train_time_s": float(r["train_time_s"]),
                            "collocation": logistic_res["hyperparameters"]["collocation"] if logistic_res else None}
    if vdp is not None:
        pinn["vdp"] = {"rel_l2": vdp["rel_l2"], "iterations": vdp["iterations"],
                       "train_time_s": vdp["train_time_s"], "collocation": vdp["hyperparameters"]["collocation"]}
    lv_T = 15.0
    if lv is not None:
        pinn["lv"] = {"rel_l2": lv["rel_l2"], "iterations": lv["iterations"], "train_time_s": lv["train_time_s"],
                      "collocation": lv["hyperparameters"]["collocation"]}
        lv_T = lv["problem"]["interval"][1]

    entries = []
    for key, label, prob in (("logistic", "logistic", logistic_problem()),
                             ("vdp", "van der Pol", vdp_problem()),
                             ("lv", "Lotka--Volterra", lv_problem(lv_T))):
        p = pinn.get(key, {})
        costs = classical_costs(prob, p.get("rel_l2"), repeats)
        entries.append({"key": key, "label": label, "pinn": p, "classical": costs})
        m = costs["rk45_matched"]
        ex.log(f"{label}: PINN relL2={p.get('rel_l2')} time={p.get('train_time_s')} | RK45 matched "
               f"{m} | DOP853 {costs['dop853']}")

    tables = {"tab_manual.tex": table_manual(manual), "tab_logistic.tex": table_logistic(logistic),
              "tab_vdp.tex": table_vdp(vdp), "tab_lv.tex": table_lv(lv), "tab_cost.tex": table_cost(entries),
              "tab_third_order.tex": table_third_order(third)}
    dirs = [ex.outdir / "tables"] + ([Path(ex.args.table_dir)] if ex.args.table_dir else [])
    for d in dirs:
        d.mkdir(parents=True, exist_ok=True)
        for name, text in tables.items():
            (d / name).write_text(text)
        ex.log(f"tables written to {d}")
    rows = []
    for e in entries:
        m = e["classical"]["rk45_matched"] or {}
        rows.append({"example": e["key"], "pinn_rel_l2": e["pinn"].get("rel_l2"),
                     "pinn_iterations": e["pinn"].get("iterations"),
                     "pinn_train_time_s": e["pinn"].get("train_time_s"),
                     "rk45_tol": m.get("tol"), "rk45_nfev": m.get("nfev"), "rk45_rel_l2": m.get("rel_l2"),
                     "rk45_time_s": m.get("time_s"), "dop853_nfev": e["classical"]["dop853"]["nfev"],
                     "dop853_rel_l2": e["classical"]["dop853"]["rel_l2"],
                     "dop853_time_s": e["classical"]["dop853"]["time_s"]})
    ex.save_table(rows, "cost_comparison")
    ex.save_results({"results_root": str(root), "timing": f"best of {repeats} repetitions",
                     "cost_comparison": [{"example": e["key"], "pinn": e["pinn"], **e["classical"]}
                                         for e in entries]})


if __name__ == "__main__":
    main()
