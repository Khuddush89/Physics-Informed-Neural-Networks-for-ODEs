"""Adjoint sensitivities with one PINN for the coupled state/adjoint (forward-backward) system.

State (logistic growth with parameters p = (r, K)):
    y' = f(y, p) = r y (1 - y/K),   y(0) = y0,   t in [0, T].
Cost (data misfit plus terminal penalty):
    J(p) = 1/2 int_0^T (y - d)^2 dt + gamma/2 (y(T) - d(T))^2,
with data d(t) generated by the logistic model with parameters (r_d, K_d).
Adjoint (terminal value problem):
    lambda' = -f_y lambda - (y - d) = -r (1 - 2y/K) lambda - (y - d),
    lambda(T) = gamma (y(T) - d(T)).
Gradient:  dJ/dr = int_0^T lambda y (1 - y/K) dt,   dJ/dK = int_0^T lambda r y^2 / K^2 dt.

One tanh MLP with two outputs represents y and lambda through the trial functions
    y_theta(t)      = y0 + (t/T) N_1(t),
    lambda_theta(t) = gamma (y_theta(T) - d(T)) + ((T - t)/T) N_2(t),
so the initial condition and the (solution-dependent) terminal condition hold exactly.  The
gradient is then evaluated with a 64-point Gauss-Legendre rule.

Checks: (i) central finite differences of J computed from the closed-form logistic solution
y(t) = K y0 e^{rt} / (K + y0 (e^{rt} - 1)) and composite Gauss-Legendre quadrature;
(ii) the classical adjoint method (exact state, adjoint integrated backward with DOP853,
rtol = atol = 1e-12).  Pointwise errors on a uniform grid of 1001 points.

Book: Chapter 6, Section "Adjoint equations and sensitivities", Figure tvp:fig:adjoint,
Table tvp:tab:adjoint.
Run:  PYTHONPATH=. python chapters/ch06_tvp/adjoint_sensitivity.py          (about 1 min, 1 core)
      PYTHONPATH=. python chapters/ch06_tvp/adjoint_sensitivity.py --quick  (smoke test)
"""
from __future__ import annotations

import numpy as np
import torch
import torch.nn as nn
from scipy.integrate import solve_ivp

from pinnode import (Example, MLP, composite_gauss_legendre, derivative, gauss_legendre, linf,
                     rel_l2, to_tensor, train, uniform)

Y0, T, GAMMA = 0.1, 6.0, 1.0
R, K = 1.0, 1.0                 # parameters at which the gradient is evaluated
R_D, K_D = 1.3, 1.2             # parameters that generated the data d(t)
WIDTH, DEPTH, N_COLLOC = 32, 3, 120


def logistic(t, r, k, y0=Y0):
    e = np.exp(r * np.asarray(t, float))
    return k * y0 * e / (k + y0 * (e - 1.0))


def data(t):
    return logistic(t, R_D, K_D)


def cost(r, k, nodes=composite_gauss_legendre(24, 16, 0.0, T)):
    s, w = nodes
    y = logistic(s, r, k)
    return 0.5 * np.sum(w * (y - data(s)) ** 2) + 0.5 * GAMMA * (logistic(T, r, k) - data(T)) ** 2


def finite_difference_gradient(h=1e-5):
    return np.array([(cost(R + h, K) - cost(R - h, K)) / (2 * h),
                     (cost(R, K + h) - cost(R, K - h)) / (2 * h)])


def classical_adjoint():
    """Exact state, adjoint integrated backward with DOP853; returns gradient and dense lambda."""
    lam_T = GAMMA * (logistic(T, R, K) - data(T))

    def rhs(t, lam):
        y = logistic(t, R, K)
        return -R * (1.0 - 2.0 * y / K) * lam - (y - data(t))

    sol = solve_ivp(rhs, (T, 0.0), [lam_T], method="DOP853", rtol=1e-12, atol=1e-12,
                    dense_output=True)
    s, w = composite_gauss_legendre(24, 16, 0.0, T)
    lam = sol.sol(s)[0]
    y = logistic(s, R, K)
    grad = np.array([np.sum(w * lam * y * (1.0 - y / K)), np.sum(w * lam * R * y ** 2 / K ** 2)])
    return grad, (lambda t: sol.sol(np.asarray(t))[0])


class StateAdjointModel(nn.Module):
    """(t) -> (y_theta, lambda_theta) with y(0) = y0 and lambda(T) = gamma (y(T) - d(T)) built in."""

    def __init__(self):
        super().__init__()
        self.net = MLP(1, 2, width=WIDTH, depth=DEPTH, activation="tanh", domain=(0.0, T))
        self.register_buffer("t_end", torch.tensor([[T]]))
        self.d_T = float(data(T))

    def forward(self, t):
        n = self.net(t)
        y = Y0 + (t / T) * n[:, :1]
        y_T = Y0 + self.net(self.t_end)[:, :1]
        lam = GAMMA * (y_T - self.d_T) + ((T - t) / T) * n[:, 1:2]
        return torch.cat([y, lam], dim=1)


def best_time(fn, repeats=5):
    """Best-of-n wall time of a classical reference computation (seconds)."""
    from pinnode import Timer
    best = float("inf")
    for _ in range(repeats):
        with Timer() as tm:
            fn()
        best = min(best, tm.elapsed)
    return best


def pinn_gradient(model, nodes):
    s, w = nodes
    with torch.no_grad():
        out = model(to_tensor(s)).numpy()
    y, lam = out[:, 0], out[:, 1]
    return np.array([np.sum(w * lam * y * (1.0 - y / K)), np.sum(w * lam * R * y ** 2 / K ** 2)])


# ----------------------------------------------------------------------------- caching
# The trained weights and the history are cached in the output folder; with --resume a rerun
# (for example after the process was interrupted) reuses them. Times are those of the original run.
RESUME_ARG = (["--resume"], {"action": "store_true",
                             "help": "reuse the training cached in the output folder"})


def load_cache(ex, tag):
    import pickle
    path = ex.path(f"cache_{tag}.pkl")
    if getattr(ex.args, "resume", False) and path.exists():
        with open(path, "rb") as fh:
            ex.log(f"resumed '{tag}' from {path.name}")
            return pickle.load(fh)
    return None


def save_cache(ex, tag, obj):
    import pickle
    with open(ex.path(f"cache_{tag}.pkl"), "wb") as fh:
        pickle.dump(obj, fh)


def main():
    ex = Example("ch06_tvp", "adjoint_sensitivity",
                 description="Adjoint sensitivity of a logistic misfit with one state/adjoint PINN",
                 default_seed=1234, extra_args=[RESUME_ARG])
    g_fd = finite_difference_gradient()
    g_adj, lam_ref_fn = classical_adjoint()
    ref_time = best_time(classical_adjoint)
    ex.log(f"J = {cost(R, K):.12e};  FD gradient = {g_fd};  classical adjoint = {g_adj};  "
           f"rel. difference = {np.linalg.norm(g_adj - g_fd) / np.linalg.norm(g_fd):.1e}")

    torch.manual_seed(ex.seed)
    model = StateAdjointModel()
    t_col = to_tensor(uniform(ex.pick(N_COLLOC, 20), 0.0, T), requires_grad=True)
    t_test = np.linspace(0.0, T, 1001)
    y_ref, lam_ref, d_test = logistic(t_test, R, K), lam_ref_fn(t_test), data(t_test)
    t_test_t = to_tensor(t_test)
    gl = gauss_legendre(64, 0.0, T)
    d_col = to_tensor(data(t_col.detach().numpy().ravel()))

    def loss_fn():
        out = model(t_col)
        y, lam = out[:, :1], out[:, 1:2]
        dy, dlam = derivative(out, t_col, 1).split(1, dim=1)
        r_state = dy - R * y * (1.0 - y / K)
        r_adj = dlam + R * (1.0 - 2.0 * y / K) * lam + (y - d_col)
        L_s, L_a = (r_state ** 2).mean(), (r_adj ** 2).mean()
        return L_s + L_a, {"state": L_s, "adjoint": L_a}

    def eval_fn():
        with torch.no_grad():
            out = model(t_test_t).numpy()
        g = pinn_gradient(model, gl)
        return {"rel_l2_y": rel_l2(out[:, 0], y_ref), "rel_l2_lambda": rel_l2(out[:, 1], lam_ref),
                "rel_err_grad": float(np.linalg.norm(g - g_fd) / np.linalg.norm(g_fd))}

    cache = load_cache(ex, "pinn")
    if cache is None:
        hist = train(model.parameters(), loss_fn, adam_iters=ex.pick(5000, 60), lr=1e-3,
                     lr_final=1e-5, lbfgs_iters=ex.pick(1000, 10), eval_fn=eval_fn, eval_every=50,
                     print_every=2000)
        save_cache(ex, "pinn", {"state": model.state_dict(), "hist": hist})
    else:
        model.load_state_dict(cache["state"])
        hist = cache["hist"]
    ex.save_history(hist, "pinn")
    with torch.no_grad():
        out = model(t_test_t).numpy()
    y_pred, lam_pred = out[:, 0], out[:, 1]
    g_pinn = pinn_gradient(model, gl)
    s, w = composite_gauss_legendre(24, 16, 0.0, T)
    with torch.no_grad():
        ys = model(to_tensor(s)).numpy()[:, 0]
        yT_pinn = float(model(to_tensor([T])).numpy()[0, 0])
    J_pinn = 0.5 * np.sum(w * (ys - data(s)) ** 2) + 0.5 * GAMMA * (yT_pinn - data(T)) ** 2
    rel = lambda a, b: float(np.abs(a - b) / np.abs(b))
    table = {
        "component": ["dJ/dr", "dJ/dK"],
        "finite_difference": g_fd, "classical_adjoint": g_adj, "pinn_adjoint": g_pinn,
        "rel_err_classical": [rel(g_adj[i], g_fd[i]) for i in range(2)],
        "rel_err_pinn": [rel(g_pinn[i], g_fd[i]) for i in range(2)],
    }
    ex.save_table(table, "gradient")
    ex.save_table({"t": t_test, "y_exact": y_ref, "y_pinn": y_pred, "lambda_ref": lam_ref,
                   "lambda_pinn": lam_pred, "data": d_test}, "predictions")
    summary = {
        "J_exact": cost(R, K), "J_pinn": J_pinn,
        "grad_fd": g_fd, "grad_classical_adjoint": g_adj, "grad_pinn": g_pinn,
        "rel_err_grad_classical": float(np.linalg.norm(g_adj - g_fd) / np.linalg.norm(g_fd)),
        "rel_err_grad_pinn": float(np.linalg.norm(g_pinn - g_fd) / np.linalg.norm(g_fd)),
        "rel_err_grad_pinn_components": table["rel_err_pinn"],
        "rel_l2_y": rel_l2(y_pred, y_ref), "linf_y": linf(y_pred, y_ref),
        "rel_l2_lambda": rel_l2(lam_pred, lam_ref), "linf_lambda": linf(lam_pred, lam_ref),
        "lambda_T_ref": float(lam_ref[-1]), "final_loss": hist.final_loss,
        "reference_time_s": ref_time,
    }
    for k_, v in summary.items():
        ex.log(f"{k_} = {v}")
    ex.save_results({
        "problem": {"y0": Y0, "T": T, "gamma": GAMMA, "r": R, "K": K, "r_data": R_D, "K_data": K_D},
        "hyperparameters": {"network": f"tanh MLP {DEPTH}x{WIDTH}, 2 outputs",
                            "collocation": f"{N_COLLOC} uniform", "adam_iters": ex.pick(5000, 60),
                            "lr": "1e-3 -> 1e-5 (cosine)", "lbfgs_iters": ex.pick(1000, 10),
                            "gradient_quadrature": "64-point Gauss-Legendre", "fd_step": 1e-5},
        **summary,
        "rel_l2": summary["rel_l2_y"], "linf": summary["linf_y"], "train_time_s": hist.train_time,
    })
    if ex.args.no_figures:
        return
    from pinnode import plotting as P          # imported only when figures are drawn

    fig, axes = P.figure(2, 2, aspect=0.72)
    ax = axes[0, 0]
    ax.plot(t_test, d_test, color=P.COLORS["muted"], lw=0.9, ls=":", label="data $d(t)$")
    P.plot_reference(ax, t_test, y_ref, label="exact $y$")
    P.plot_prediction(ax, t_test, y_pred, label=r"PINN $y_\theta$", k=0, markevery=(40, 100))
    ax.set_xlabel("$t$")
    ax.set_ylabel("state")
    ax.legend(loc="lower right")

    ax = axes[0, 1]
    P.plot_reference(ax, t_test, lam_ref, label=r"reference $\lambda$")
    P.plot_prediction(ax, t_test, lam_pred, label=r"PINN $\lambda_\theta$", k=1,
                      markevery=(70, 100))
    ax.set_xlabel("$t$")
    ax.set_ylabel("adjoint")
    ax.legend(loc="lower right")

    ax = axes[1, 0]
    P.plot_history(ax, hist, parts=["state", "adjoint"],
                   labels={"state": "state residual", "adjoint": "adjoint residual"})
    ax.legend(loc="lower left")

    ax = axes[1, 1]
    P.plot_metric(ax, hist, "rel_l2_y", label=r"$y_\theta$ (rel. $L^2$)", k=0)
    P.plot_metric(ax, hist, "rel_l2_lambda", label=r"$\lambda_\theta$ (rel. $L^2$)", k=1,
                  show_switch=False)
    P.plot_metric(ax, hist, "rel_err_grad", label=r"$\nabla_p J$ (rel. error)", k=2,
                  show_switch=False, ylabel="relative error")
    P.label_panels(axes)
    ex.savefig(fig, "adjoint_sensitivity")


if __name__ == "__main__":
    main()
