#!/usr/bin/env python3
"""Write the LaTeX tables of Chapter 12 from the results.json files of the chapter scripts.

The tables contain wall-clock times, which depend on the machine and its load; re-run the
scripts (one at a time, one thread) and then this file to refresh every number:

    PYTHONPATH=. python chapters/ch12_further_classes/<script>.py      # for each script
    python chapters/ch12_further_classes/_make_tables.py               # -> ../book/figures/ch12/tab_*.tex

Each output file holds only a booktabs ``tabular``; caption, label and float live in the
chapter source (``\\input{figures/ch12/tab_<name>}``).
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "outputs" / "ch12_further_classes"
# the book sources live next to the repository while the book is being written; otherwise the
# tables go to the output folder of the chapter
_BOOK = REPO.parent / "book" / "figures" / "ch12"
DEFAULT_DEST = _BOOK if _BOOK.parent.is_dir() else OUT / "tables"


def load(name):
    p = OUT / name / "results.json"
    if not p.exists():
        raise FileNotFoundError(f"{p} missing: run chapters/ch12_further_classes/{name}.py first")
    return json.loads(p.read_text())


def num(x, d=2):
    """siunitx number: plain with d+1 significant digits for 0.1 <= |x| < 1000, otherwise
    scientific notation without a '+' in the exponent (the book sets retain-explicit-plus)."""
    if x is None or (isinstance(x, float) and not math.isfinite(x)):
        return "--"
    if x != 0 and 0.1 <= abs(x) < 1000:
        return f"\\num{{{float(f'{x:.{d + 1}g}'):g}}}"
    mant, ex = f"{x:.{d}e}".split("e")
    return f"\\num{{{mant}e{int(ex)}}}"


def sec(x):
    """Wall-clock seconds: two significant digits below 10 s, whole seconds above."""
    if x is None:
        return "--"
    if x < 10:
        return f"\\num{{{x:.2g}}}"
    return f"\\num{{{x:.0f}}}"


def fixed(x, d):
    return "--" if x is None else f"\\num{{{x:.{d}f}}}"


def write(dest: Path, name: str, lines):
    dest.mkdir(parents=True, exist_ok=True)
    text = "% generated by repo/chapters/ch12_further_classes/_make_tables.py -- do not edit\n" + "\n".join(lines) + "\n"
    (dest / f"tab_{name}.tex").write_text(text)
    print(f"wrote {dest / f'tab_{name}.tex'}")


def table_robertson(dest):
    r = load("stiff_robertson")
    lines = [r"\begin{tabular}{llcccr}", r"\toprule",
             r"Method & Setting & $\relLtwo(y_1)$ & $\relLtwo(y_2)$ & $\relLtwo(y_3)$ & Time [s] \\",
             r"\midrule"]
    for row in r["summary"]:
        if row["method"] == "PINN":
            continue
        if row["rtol"] not in (1e-4, 1e-6, 1e-10):
            continue
        setting = f"$\\mathrm{{rtol}}=10^{{{int(round(math.log10(row['rtol'])))}}}$"
        lines.append(f"{row['method']} & {setting} & {num(row['rel_l2_y1'], 1)} & {num(row['rel_l2_y2'], 1)} & "
                     f"{num(row['rel_l2_y3'], 1)} & {sec(row['time_s'])} \\\\")
    lines.append(r"\midrule")
    for row in r["summary"]:
        if row["method"] != "PINN":
            continue
        lines.append(f"PINN & {row['setting']} & {num(row['rel_l2_y1'], 1)} & {num(row['rel_l2_y2'], 1)} & "
                     f"{num(row['rel_l2_y3'], 1)} & {sec(row['time_s'])} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(dest, "robertson", lines)


def table_lane_emden(dest):
    r = load("lane_emden")
    lines = [r"\begin{tabular}{clccccc}", r"\toprule",
             r"$m$ & Reference & $\relLtwo$ & Max.\ error & $\xi_1$ (PINN) & $\xi_1$ (ref.) & "
             r"$\omega$ (PINN) / (ref.) \\", r"\midrule"]
    for row in r["summary"]:
        ref = "exact" if row["reference"] == "exact" else "series + DOP853"
        om = "--" if row["omega_ref"] is None else f"{fixed(row['omega_pinn'], 5)} / {fixed(row['omega_ref'], 5)}"
        lines.append(f"{row['m']} & {ref} & {num(row['rel_l2'], 1)} & {num(row['linf'], 1)} & "
                     f"{fixed(row['xi1_pinn'], 6)} & {fixed(row['xi1_ref'], 6)} & {om} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(dest, "lane_emden", lines)


def table_eigen(dest):
    r = load("sturm_liouville")
    lines = [r"\begin{tabular}{cccccc}", r"\toprule",
             r"Problem & $k$ & $\lambda_k$ (reference) & $\lambda_k$ (PINN) & Rel.\ error & "
             r"Eigenfunction $\relLtwo$ \\", r"\midrule"]
    for i, row in enumerate(r["summary"]):
        if i == 3:
            lines.append(r"\midrule")
        lines.append(f"{row['problem']} & {row['k']} & {fixed(row['lambda_ref'], 10)} & "
                     f"{fixed(row['lambda_pinn'], 10)} & {num(row['lambda_rel_err'], 1)} & "
                     f"{num(row['eigfun_rel_l2'], 1)} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(dest, "eigen", lines)


def table_summary(dest):
    """One line per worked example: accuracy and training time (Section labels in the chapter)."""
    rows = []
    rob = load("stiff_robertson")
    for row in rob["summary"]:
        if row["method"] == "PINN":
            err = max(row["rel_l2_y1"], row["rel_l2_y2"], row["rel_l2_y3"])
            rows.append(("Robertson kinetics", f"{row['setting']} PINN", err, row["time_s"]))
    le = load("lane_emden")
    for row in le["summary"]:
        rows.append(("Lane--Emden", f"$m={row['m']}$", row["rel_l2"], row["train_time_s"]))
    dde = load("delay_method_of_steps")
    for row in dde["summary"]:
        name = "global network" if row["formulation"] == "global" else "method of steps"
        rows.append(("Delay equation", name, row["rel_l2"], row["train_time_s"]))
    fr = load("fractional_relaxation")
    n_max = max(row["N"] for row in fr["convergence"])
    for row in fr["convergence"]:
        if row["N"] == n_max:
            rows.append(("Fractional relaxation", f"$\\alpha={row['alpha']}$, {row['mesh']}, $N={n_max}$",
                         row["pinn_rel_l2"], row["train_time_s"]))
    dae = load("dae_nonlinear_resistor")
    for row in dae["summary"]:
        name = ("hard (Newton layer)" if row["formulation"] == "hard"
                else f"penalty, $w_a={int(row['w_a'])}$")
        rows.append(("Index-1 DAE", name, max(row["rel_l2_y"], row["rel_l2_z"]), row["train_time_s"]))
    sl = load("sturm_liouville")
    for prob in ("A", "B"):
        sel = [row for row in sl["summary"] if row["problem"] == prob]
        rows.append(("Sturm--Liouville", f"problem {prob}, $k=1,2,3$", max(r_["eigfun_rel_l2"] for r_ in sel),
                     sum(r_["train_time_s"] for r_ in sel)))
    ts = load("time_scales")
    tsname = {"continuous": r"$\mathbb{T}=[0,7]$", "discrete": r"$\mathbb{T}=\{0,\dots,7\}$",
              "hybrid_single": r"$\mathbb{P}_{1,1}$, single output",
              "hybrid_heads": r"$\mathbb{P}_{1,1}$, one head per interval"}
    for row in ts["summary"]:
        rows.append(("Time scales", tsname[row["run"]], row["rel_l2"], row["train_time_s"]))
    lines = [r"\begin{tabular}{llcr}", r"\toprule",
             r"Example & Formulation & $\relLtwo$ error & Training time [s] \\", r"\midrule"]
    last = None
    for ex_name, form, err, t in rows:
        if last is not None and ex_name != last:
            lines.append(r"\addlinespace[2pt]")
        lines.append(f"{ex_name if ex_name != last else ''} & {form} & {num(err, 1)} & {sec(t)} \\\\")
        last = ex_name
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(dest, "summary", lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dest", default=str(DEFAULT_DEST), help="output folder (default: book/figures/ch12)")
    args = ap.parse_args()
    dest = Path(args.dest)
    for fn in (table_robertson, table_lane_emden, table_eigen, table_summary):
        try:
            fn(dest)
        except FileNotFoundError as err:
            print(f"skipped {fn.__name__}: {err}")


if __name__ == "__main__":
    main()
